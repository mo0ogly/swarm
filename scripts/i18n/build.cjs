'use strict';
const fs = require('node:fs'), crypto = require('node:crypto');
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: build.cjs [--check]');
const check = args.includes('--check');
const artifacts = [
  {source:'locales/en.json', output:'web/i18n-en.js', prefix:"'use strict';\n// Generated by npm run i18n:build. Edit locales/en.json.\nglobalThis.SwarmEnglish = "},
  {source:'locales/trust-actions-en.json', output:'web/trust-actions-en.js', prefix:"'use strict';\nglobalThis.SwarmEnglish = "}
].map(artifact => {
  const input = fs.readFileSync(artifact.source), expected = artifact.prefix + JSON.stringify(JSON.parse(input), null, 2) + ';\n';
  return {...artifact, input, expected};
});
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');
for (const artifact of artifacts) {
  if (check) {
    const actual = fs.readFileSync(artifact.output);
    if (!actual.equals(Buffer.from(artifact.expected))) throw new Error('Generated artifact differs: ' + artifact.output);
  } else fs.writeFileSync(artifact.output, artifact.expected);
  console.log(JSON.stringify({mode:check?'check':'build', source:artifact.source, source_sha256:sha256(artifact.input), output:artifact.output, output_sha256:sha256(artifact.expected), status:'pass'}));
}
