"""Derive a release sitemap from public home links, never from a recursive crawl.

Only the existing six presentation routes and linked bilingual Swarm article
pairs are eligible. Review/private/unlinked files remain excluded. Generation
changes only the managed sitemap in an isolated candidate; IO/validation errors
propagate before the caller may activate it. No network or service operations.
"""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urljoin, urlparse
import hashlib
import os
import re
import xml.etree.ElementTree as ET

ORIGIN = 'https://swarm-agentic.com/'
ROOT_PAIRS = [('fr.html','en.html'),('decouvrir.html','discover.html'),('fonctionnement.html','how-it-works.html')]
MARKER = b'<!-- Generated by Swarm seo_metadata.py; public routes only. -->'
ARTICLE = re.compile(r'articles/(swarm-[a-z0-9]+(?:-[a-z0-9]+)*)/(fr|en)\.html\Z')


class Page(HTMLParser):
    """Read public links, language and indexing metadata without executing HTML."""
    def __init__(self, text):
        """Parse one UTF-8 page; malformed encoding is rejected by the caller."""
        super().__init__();self.links=[];self.lang=None;self.noindex=False;self.canonicals=[];self.feed(text)

    def handle_starttag(self, tag, attrs):
        """Collect only the attributes relevant to publication eligibility."""
        a=dict(attrs)
        if tag=='html':self.lang=a.get('lang')
        if tag=='a' and a.get('href'):self.links.append(a['href'])
        if tag=='meta' and a.get('name','').lower() in ('robots','googlebot'):
            self.noindex |= bool(set(re.split(r'[\s,]+',a.get('content','').lower())) & {'noindex','none'})
        if tag=='link' and 'canonical' in a.get('rel','').split():self.canonicals.append(a.get('href'))


def read_public(root, name, lang):
    """Validate one eligible regular local page; refuse symlinks/noindex/mismatch."""
    path=root/name
    if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(root.resolve()):
        raise ValueError('Missing or unsafe public page: '+name)
    page=Page(path.read_text(encoding='utf-8'))
    if page.lang!=lang or page.noindex:
        raise ValueError('Public page language/noindex conflict: '+name)
    if page.canonicals and page.canonicals != [ORIGIN+name]:
        raise ValueError('Public canonical conflict: '+name)
    return page


def render_sitemap(root):
    """Return XML bytes and exact public routes from the candidate's home links.

    Public pages must exist in both languages and be indexable. Private or
    unlinked HTML is not inferred public merely because it exists on disk.
    A linked article missing its counterpart refuses instead of disappearing.
    """
    root=Path(root)
    pages={name:lang for pair in ROOT_PAIRS for name,lang in zip(pair,('fr','en'))}
    linked={'fr':set(),'en':set()}
    for lang in ('fr','en'):
        home=read_public(root,lang+'.html',lang)
        for href in home.links:
            url=urlparse(urljoin(ORIGIN+lang+'.html',href))
            if url.scheme!='https' or url.netloc!='swarm-agentic.com':continue
            match=ARTICLE.fullmatch(url.path.lstrip('/'))
            if match:
                slug,target_lang=match.groups()
                if target_lang==lang:linked[lang].add(slug)
    if linked['fr']!=linked['en']:
        raise ValueError('Public homepage article languages differ')
    for slug in sorted(linked['fr']):
        for lang in ('fr','en'):pages[f'articles/{slug}/{lang}.html']=lang
    for name,lang in pages.items():read_public(root,name,lang)
    namespace='http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('',namespace);tree=ET.Element('{'+namespace+'}urlset')
    for name in sorted(pages):
        url=ET.SubElement(tree,'{'+namespace+'}url');ET.SubElement(url,'{'+namespace+'}loc').text=ORIGIN+name
    data=ET.tostring(tree,encoding='utf-8',xml_declaration=True)+b'\n'+MARKER+b'\n'
    return data,sorted(pages)


def regenerate_sitemap(root):
    """Atomically generate and reread the managed candidate sitemap.

    Refuse overwriting an unmanaged file. All parsing precedes writes. A failed
    temporary write/fsync leaves the previous sitemap intact; failed replacement
    or reread propagates. The caller must not publish this candidate on failure.
    Existing equal bytes need no write. Returns generated hash and route list.
    """
    root=Path(root);data,pages=render_sitemap(root);target=root/'sitemap.xml'
    if target.is_symlink():raise ValueError('Sitemap symlink refused')
    old=target.read_bytes() if target.exists() else None
    if old is not None and MARKER not in old:raise ValueError('Unmanaged sitemap refused')
    if old!=data:
        temporary=target.with_name('sitemap.xml.publication-next')
        with temporary.open('xb') as stream:
            stream.write(data);stream.flush();os.fsync(stream.fileno())
        temporary.chmod(0o644);os.replace(temporary,target)
    if target.read_bytes()!=data:raise ValueError('Generated sitemap reread differs')
    return {'sha256':hashlib.sha256(data).hexdigest(),'pages':pages,'urls':len(pages),'changed':old!=data}


def verify_sitemap(root):
    """Read-only equality check against the exact pages eligible in this release."""
    data,pages=render_sitemap(root)
    if (Path(root)/'sitemap.xml').read_bytes()!=data:raise ValueError('Stale or mismatching publication sitemap')
    return {'sha256':hashlib.sha256(data).hexdigest(),'urls':len(pages),'pages':pages}
