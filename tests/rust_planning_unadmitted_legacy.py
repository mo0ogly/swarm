#!/usr/bin/env python3
"""Verify unknown legacy grant evidence stays blocked, using retained owned RED.

Requires the original spawn-failure fixture generated by the old binary and its
healthy traced control. Reads fixture SQL only, invokes public reconcile only,
and never upgrades a missing observation, starts a model, or deletes evidence.
"""
import argparse,json,subprocess,traceback,hashlib
from pathlib import Path
from types import SimpleNamespace
import rust_planning_native_run as native
import rust_agent_model_route as fixture

def main():
    """Correlate retained command/claim/Root; assert exact rejection/no mutation.

    The caller must supply the owned historical RED directory, not a live Root.
    Its original recipe integrity is verified independently by the recipe runner.
    A readable row or absent child is never enough to manufacture no-grant proof.
    """
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--binary',required=True,type=Path);p.add_argument('--original',required=True,type=Path);p.add_argument('--output',required=True,type=Path);a=p.parse_args();out=a.output.resolve();out.mkdir(exist_ok=False);binary=a.binary.resolve();old=a.original.resolve()
    command_path=old/'spawn-refused-command.json';command=json.loads(command_path.read_bytes())['argv'];root=Path(command[command.index('--root')+1]);request_path=Path(command[command.index('--input')+1]);request=json.loads(request_path.read_bytes());claim=request['claim_id'];work=command[command.index('run')+1]
    assert root.resolve().parent==Path('/tmp') and root.name.startswith('swarm-model83-')
    original=json.loads((old/'inputs.json').read_bytes());assert fixture.digest(Path(original['binary']).read_bytes())==original['binary_sha256'];assert 'EAGAIN' in (old/'spawn-refused-process.trace').read_text()
    helpers=[Path(__file__),Path(native.__file__),Path(fixture.__file__)];inputs=dict(binary=str(binary),binary_sha256=fixture.digest(binary.read_bytes()),original_binary_sha256=original['binary_sha256'],command_sha256=fixture.digest(command_path.read_bytes()),request_sha256=fixture.digest(request_path.read_bytes()),sources={str(p):fixture.digest(p.read_bytes()) for p in helpers});fixture.publish(out/'inputs.json',inputs)
    def observe():
        """Read logical SQL and actual claim shape, closing with checked helper."""
        with native.database(SimpleNamespace(root=root)) as db:
            row=db.execute('SELECT work_id,phase,permission,child_pid FROM native_planning_runs WHERE claim_id=?',[claim]).fetchone();assert row==(work,'claimed',0,None),row
            return fixture.digest(('\n'.join(db.iterdump())).encode())
    try:
        before=observe();witness=set(root.glob('model-received-*.json'));assert not witness
        argv=[str(binary),'planning','reconcile',claim,'--root',str(root),'--json'];fixture.publish(out/'command.json',dict(argv=argv));r=subprocess.run(argv,capture_output=True);fixture.publish(out/'stdout',r.stdout);fixture.publish(out/'stderr',r.stderr);wire=json.loads(r.stderr)
        assert r.returncode!=0 and 'planning-failure-evidence-required' in str(wire),wire
        assert observe()==before and set(root.glob('model-received-*.json'))==witness
        assert fixture.digest(binary.read_bytes())==inputs['binary_sha256'] and all(fixture.digest(Path(p).read_bytes())==h for p,h in inputs['sources'].items())
        result=dict(status='PASS',legacy_unknown_refused=True,no_state_mutation=True,no_inference=True,root=str(root));fixture.publish(out/'result.json',result);print(json.dumps(result))
    except BaseException:fixture.publish(out/'failure.json',dict(status='FAIL',cause=traceback.format_exc()));raise

if __name__=='__main__':main()
